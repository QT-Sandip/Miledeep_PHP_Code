    function getRequestDetails($RequestBody)
    {



        $RecordsPerPage = 100;
        $IBTID = $RequestBody['IBTID'];
        $ibtType = $RequestBody['ibtType'];
        $ColdStore = $RequestBody['ColdStore'];
        $Month = $RequestBody['Month'];
        $Year = $RequestBody['Year'];
        $Type = $RequestBody['Type'];
        $SearchKey = $RequestBody['SearchKey'];
        $PageNo = $RequestBody['PageNo'];
        $LoadAll = $RequestBody['LoadAll'];
        if ($Type == 'getAutogeneratedIBTCode' && $IBTID == '') {
            $OrderDate = $RequestBody['OrderDate'];
            $StoreID = $RequestBody['FromStore'];
            $PlantID = $RequestBody['PlantID'];

            if ($PlantID != '' && $OrderDate != '') {
                $IBTCode = $this->getAutoGeneratedIBTCode($OrderDate, $PlantID);
                $data['Error'] = null;
                $data['Msg'] = 'Success';
                $data['IBTCode'] = isset($IBTCode) ? $IBTCode : 0;
            }
        } else {

            $Query = '';


            if ($IBTID != "") {
                $Query .= "  CIBTRD.IBTID = $IBTID";
            }
            $SQuery = '';
            if ($ColdStore != null && trim($ColdStore) != '' && $ColdStore != 'undefined') {
                if ($ibtType == 0) {
                    $SQuery .= " and   CIBTRD.FromStore = '$ColdStore'";
                } else {
                    $SQuery .= " and  CIBTRD.FromStore != '$ColdStore' and CIBTRD.ToStore= '$ColdStore'  ";
                }
            }
            $DateFilter = '';
            if ($Month != null && $Year != null && trim($Month) != '' && trim($Year) != '' && $Month != 'undefined' && $Year != 'undefined') {
                $DateFilter = " where Month(OrderDate)= '$Month' and Year(OrderDate)= '$Year'";
            }


            $RecordsPerPage = 100;
            $LimitMax = ($PageNo - 1) * $RecordsPerPage;
            $Limit = 'LIMIT ' . $RecordsPerPage . ' OFFSET ' . $LimitMax;

            if ($LoadAll == 1) {
                $Limit = '';
            }

            if ($SearchKey != null && trim($SearchKey) != '' && $SearchKey != 'undefined') {
                $Query = " and CONCAT_WS('', IBTOrderNumber,OrderDate,FromStore,ToStore) LIKE '%$SearchKey%'";
            }

            $sqlCount = "SELECT COUNT(DISTINCT IBTID) as Total  FROM `CsIBTRequestDetails` $DateFilter";

            $stmt = $this->conn->prepare($sqlCount);
            $stmt->execute();
            $dataRow = $stmt->fetch(PDO::FETCH_ASSOC);
            $TotalCount = $dataRow['Total'];
            $PageCount = ceil($TotalCount / $RecordsPerPage);

            // $sqlFields = "CIBTRD.IBTID, CIBTRD.IBTOrderNumber, CIBTRD.OrderDate, CIBTRD.FromStore, 
            // CIBTRD.ToStore, CIBTRD.Remarks, CSR.StoreName AS FromStoreName, CSR2.StoreName AS ToStoreName, 
