            //     $sqlQuery = "SELECT $sqlFields FROM CsIBTRequestDetails AS CIBTRD
            //     LEFT JOIN CsStores AS CSR ON CIBTRD.FromStore=CSR.StoreID
            //     LEFT JOIN CsStores AS CSR2 ON CIBTRD.ToStore=CSR2.StoreID
