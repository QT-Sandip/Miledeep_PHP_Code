                $ArrayRequestList['PackingStyle'] = $dataInward['PackingStyle'];
                $ArrayRequestList['ProductDescription'] = $dataInward['ProductDescription'];
                
                $ArrayRequestData[] = $ArrayRequestList;
            }

            if (count($ArrayRequestData) < $RecordsPerPage) {
                $RecordsAval = 0;
            } else {
                $RecordsAval = 1;
