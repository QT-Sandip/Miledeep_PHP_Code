                $BalanceLoose = $NoOfLooseBags - $ActualLooseBags;

                if ($BalanceMcs < 0 && $BalanceLoose > 0) {

                    $LooseMcs = floor($BalanceLoose / $TotalSlabsProd);

                    // Don't convert more MCs than required
                    $RequiredMcs = abs($BalanceMcs);

                    if ($LooseMcs > $RequiredMcs) {
                        $LooseMcs = $RequiredMcs;
                    }

                    $BalanceLoose -= ($LooseMcs * $TotalSlabsProd);
                    $BalanceMcs += $LooseMcs;
                }

                $ArrayRequestList['SNO'] = ++$i;
                $ArrayRequestList['IBTID'] = $dataRow['IBTID'];
                $ArrayRequestList['ProductionID'] = $ProductionID;
                $ArrayRequestList['IBTOrderNumber'] = $dataRow['IBTOrderNumber'];
                $ArrayRequestList['OrderDate'] = $dataRow['OrderDate'];
                $ArrayRequestList['FromStore'] = $dataRow['FromStore'];
                $ArrayRequestList['FromStoreName'] = $dataRow['FromStoreName'];
                $ArrayRequestList['ToStore'] = $dataRow['ToStore'];
                $ArrayRequestList['ToStoreName'] = $dataRow['ToStoreName'];
                $ArrayRequestList['TotalMcs'] = $NoofMcs;
                $ArrayRequestList['TotalBags'] = $NoOfLooseBags;
                $ArrayRequestList['ActualMcs'] = $dataRow['ActualMcs'];
                $ArrayRequestList['ActualLooseBags'] = $dataRow['ActualLooseBags'];
                $ArrayRequestList['BalanceMcs'] = $BalanceMcs;
                $ArrayRequestList['BalanceLoose'] = $BalanceLoose;
                if($BalanceMcs > 0 || $BalanceLoose > 0){
