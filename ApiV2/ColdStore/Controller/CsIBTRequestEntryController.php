            $data['PageCount'] = $PageCount;
            $data['RecordsAval'] = $RecordsAval;
            $data['IBTCode'] = 0;
        }
        return $data;
    }

    public function getAutoGeneratedIBTCode($OrderDate, $PlantID)
    {
        // $sqlgetmaxIBTCode = " SELECT max(AutoIBTNo) as AutoIBTNo FROM CsIBTRequestDetails as CIRD 
        // left join CsStores as CS on CS.StoreID=CIRD.FromStore 
        // left join RmProcessingStations as RPS on RPS.ProcessingStationID=CS.ProductionPlantID 
        // WHERE month(OrderDate)=month('$OrderDate') and year(OrderDate)=year('$OrderDate') and ProductionPlantID='$PlantID'";
        $sqlgetmaxIBTCode = " SELECT max(AutoIBTNo) as AutoIBTNo FROM CsIBTRequestDetails as CIRD 
        WHERE month(OrderDate)=month('$OrderDate') and year(OrderDate)=year('$OrderDate') and FromPlantID='$PlantID'";

        $stmtgetmaxIBTCode = $this->conn->prepare($sqlgetmaxIBTCode);
        $stmtgetmaxIBTCode->execute();
        $dataRowgetmaxIBTCode = $stmtgetmaxIBTCode->fetch(PDO::FETCH_ASSOC);

        $sqlPlantCode = "SELECT ProdCode as PlantCode FROM RmProcessingStations WHERE ProcessingStationID = '$PlantID'";
        $stmtPlantCode = $this->conn->prepare($sqlPlantCode);
        $stmtPlantCode->execute();
        $dataPlantCode = $stmtPlantCode->fetch(PDO::FETCH_ASSOC);

        $AutoIBTNo = $dataRowgetmaxIBTCode['AutoIBTNo'] + 1;
        $PlantCode = $dataPlantCode['PlantCode'];

        $AutoIBTCode = str_replace("O", "0", $AutoIBTNo);
        $AutoIBTCode = ltrim($AutoIBTCode, "0");
        $AutoIBTCode = preg_replace("/[^0-9]/", "", $AutoIBTCode);
        $AutoIBTCode = sprintf('%04d', $AutoIBTCode);


        $AutoIBTCode = $PlantCode . '-' . sprintf('%03d', $AutoIBTNo);

        $ArrayIBTCode['AutoIBTNo'] = $AutoIBTNo;
        $ArrayIBTCode['IBTCode'] = $AutoIBTCode;

        return $ArrayIBTCode;
    }
