function validatePostData($authToken, $RequestBody)
{

    $isValid = false;
    $error = null;

    if (!isset($authToken) && empty($authToken)) {
        $error = 'Token Not Found';
    } else  if (!isset($RequestBody['UserName']) || empty($RequestBody['UserName'])) {
        $error = 'Agent Name not Found';
    } else  if (!isset($RequestBody['PanNumber']) || empty($RequestBody['PanNumber'])) {
        $error = 'PanNumber not Found';
    } else if (strlen($RequestBody['PanNumber']) !== 10) {
        $error = 'PanNumber must be exactly 10 digits';
    }
    // else  if (!isset($RequestBody['GstNo']) || empty($RequestBody['GstNo'])) {
    //     $error = 'GST Number not Found';
    // }
