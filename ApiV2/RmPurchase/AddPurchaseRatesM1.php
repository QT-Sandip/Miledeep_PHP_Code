include_once '../Config/Config.php';
include_once 'Controller/AddPurchaseRatesM1Controller.php';

$database = new Database();
$restApi = new REST();
$isValid = false;

$authToken = $restApi->getRequestHeader();
$RequestBody = $restApi->getRequestBody();
$RequestMethod = $restApi->get_request_method();

if ($RequestMethod == 'GET') {
    $data = validateGetData($authToken, $RequestBody);
} else if ($RequestMethod == 'POST') {
    $data = validatePostData($authToken, $RequestBody);
} else {
}


if ($data['IsValid']) {
    $db = $database->getConnection($authToken);
    if ($db != null) {
        $Controller = new AddPurchaseRatesM1Controller($db);
        if ($RequestMethod == 'GET') {
            $responseData = $Controller->getRmCountDetails($RequestBody);
        } else if ($RequestMethod == 'POST') {
            if ($RequestBody['Type'] && $RequestBody['Type'] == 'copy') {
                $responseData = $Controller->copyRmCountDetails($RequestBody);
            } else if ($RequestBody['Type'] && $RequestBody['Type'] == 'delete') {
                $responseData = $Controller->deleteRmCountDetails($RequestBody);
            } else {
                $responseData = $Controller->postRmCountDetails($RequestBody);
            }
        }

        $responseData = json_encode($responseData);
        $restApi->response($responseData, 200);
    }
} else {
    $responseData['Error'] = $data['Error'];
    $responseData['Msg'] = $data['Error'];
    $responseData = json_encode($responseData);
    $restApi->response($responseData, 200);
}

